-- Mutasi aset: riwayat pindah ruangan per aset (dari, ke, tanggal, petugas, alasan). Khusus barang aset;
-- barang habis pakai tetap hanya masuk/keluar gudang. Requires ops-core.sql and ops-aset.sql. Safe to re-run.
-- A trigger records every change of barang_aset.ruangan_id, so "Pindahkan" and "Ubah" in Daftar aset are logged too.

BEGIN;

CREATE TABLE IF NOT EXISTS simbar.mutasi_aset (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barang_aset_id bigint NOT NULL REFERENCES simbar.barang_aset(id) ON DELETE CASCADE,
    dari_ruangan_id bigint REFERENCES simbar.ruangan(id) ON DELETE SET NULL,
    ke_ruangan_id bigint REFERENCES simbar.ruangan(id) ON DELETE SET NULL,
    -- Room names as they were at the time, so the history stays readable after a room is renamed or deleted.
    dari_ruangan text NOT NULL,
    ke_ruangan text NOT NULL,
    tanggal date NOT NULL,
    alasan text,
    created_by bigint REFERENCES simbar.users(id) ON DELETE SET NULL,
    created_at timestamp without time zone NOT NULL
);
CREATE INDEX IF NOT EXISTS mutasi_aset_aset_idx ON simbar.mutasi_aset (barang_aset_id, tanggal DESC, id DESC);
CREATE INDEX IF NOT EXISTS mutasi_aset_tanggal_idx ON simbar.mutasi_aset (tanggal DESC, id DESC);
ALTER TABLE simbar.mutasi_aset ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON simbar.mutasi_aset FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION simbar.record_mutasi_aset()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    moved_on date := coalesce(nullif(current_setting('simbar.mutasi_tanggal', true), '')::date, simbar.local_today());
    reason text := nullif(current_setting('simbar.mutasi_alasan', true), '');
BEGIN
    INSERT INTO simbar.mutasi_aset (barang_aset_id, dari_ruangan_id, ke_ruangan_id, dari_ruangan, ke_ruangan, tanggal, alasan, created_by, created_at)
    VALUES (NEW.id, OLD.ruangan_id, NEW.ruangan_id,
        coalesce((SELECT nama_ruangan FROM simbar.ruangan WHERE id = OLD.ruangan_id), '-'),
        coalesce((SELECT nama_ruangan FROM simbar.ruangan WHERE id = NEW.ruangan_id), '-'),
        moved_on, reason, (SELECT id FROM simbar.users WHERE auth_user_id = auth.uid()), simbar.local_now());
    RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS barang_aset_mutasi ON simbar.barang_aset;
CREATE TRIGGER barang_aset_mutasi AFTER UPDATE OF ruangan_id ON simbar.barang_aset
    FOR EACH ROW WHEN (OLD.ruangan_id IS DISTINCT FROM NEW.ruangan_id)
    EXECUTE FUNCTION simbar.record_mutasi_aset();

-- Pindah ruangan from the Mutasi menu: one or more assets to one room, with the date it happened and a reason.
CREATE OR REPLACE FUNCTION public.simbar_mutasi_aset_move(aset_ids bigint[], target_room bigint, moved_on date, reason text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    actor simbar.users%ROWTYPE := simbar.require_profile(ARRAY['admin', 'admin_gudang']);
    room_name text;
    note text := nullif(btrim(coalesce(reason, '')), '');
    moved integer;
    skipped integer;
BEGIN
    IF aset_ids IS NULL OR cardinality(aset_ids) NOT BETWEEN 1 AND 500 THEN
        RAISE check_violation USING MESSAGE = 'Pilih minimal 1 aset terlebih dahulu.';
    END IF;
    IF moved_on IS NULL OR moved_on > simbar.local_today() OR moved_on < DATE '2000-01-01' THEN
        RAISE check_violation USING MESSAGE = 'Tanggal pindah tidak valid atau melebihi hari ini.';
    END IF;
    IF char_length(note) > 500 THEN
        RAISE check_violation USING MESSAGE = 'Alasan maksimal 500 karakter.';
    END IF;
    SELECT nama_ruangan INTO room_name FROM simbar.ruangan WHERE id = target_room AND is_active;
    IF room_name IS NULL THEN
        RAISE check_violation USING MESSAGE = 'Ruangan tujuan tidak aktif atau tidak ditemukan.';
    END IF;
    SELECT count(*) INTO skipped FROM simbar.barang_aset WHERE id = ANY (aset_ids) AND ruangan_id = target_room;
    PERFORM set_config('simbar.mutasi_tanggal', moved_on::text, true), set_config('simbar.mutasi_alasan', coalesce(note, ''), true);
    UPDATE simbar.barang_aset SET ruangan_id = target_room, updated_at = simbar.local_now()
    WHERE id = ANY (aset_ids) AND ruangan_id <> target_room;
    GET DIAGNOSTICS moved = ROW_COUNT;
    PERFORM set_config('simbar.mutasi_tanggal', '', true), set_config('simbar.mutasi_alasan', '', true);
    IF moved = 0 THEN
        RAISE check_violation USING MESSAGE = 'Aset yang dipilih sudah berada di ruangan ' || room_name || '.';
    END IF;
    PERFORM simbar.write_log(actor.id, 'mutasi_aset', 'Pindah ruangan ' || moved || ' aset ke ' || room_name
        || CASE WHEN skipped > 0 THEN ' (' || skipped || ' aset dilewati)' ELSE '' END);
    RETURN jsonb_build_object('moved', moved, 'skipped', skipped, 'room', room_name);
END;
$function$;

-- filters: {search, ruangan (dari atau ke), from, to, aset}. page_number 0 returns every match (export).
CREATE OR REPLACE FUNCTION public.simbar_mutasi_aset_list(filters jsonb DEFAULT '{}', page_number integer DEFAULT 1)
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    search_text text := btrim(coalesce(filters->>'search', ''));
    pattern text;
    room bigint := nullif(filters->>'ruangan', '')::bigint;
    aset bigint := nullif(filters->>'aset', '')::bigint;
    date_from date := nullif(filters->>'from', '')::date;
    date_to date := nullif(filters->>'to', '')::date;
    result jsonb;
BEGIN
    PERFORM simbar.require_profile(ARRAY['admin', 'admin_gudang', 'staff']);
    IF char_length(search_text) > 100 OR page_number IS NULL OR page_number NOT BETWEEN 0 AND 10000 THEN
        RAISE invalid_parameter_value USING MESSAGE = 'Filter mutasi aset tidak valid.';
    END IF;
    pattern := '%' || replace(replace(replace(search_text, '!', '!!'), '%', '!%'), '_', '!_') || '%';

    WITH matched AS MATERIALIZED (
        SELECT m.id, m.tanggal, a.id AS aset_id, a.kode_aset AS code, a.nama_aset AS name, a.merk,
               m.dari_ruangan AS dari, m.ke_ruangan AS ke, m.alasan, u.name AS petugas, m.created_at
        FROM simbar.mutasi_aset m
        JOIN simbar.barang_aset a ON a.id = m.barang_aset_id
        LEFT JOIN simbar.users u ON u.id = m.created_by
        WHERE (a.nama_aset ILIKE pattern ESCAPE '!' OR a.kode_aset ILIKE pattern ESCAPE '!' OR m.alasan ILIKE pattern ESCAPE '!')
          AND (room IS NULL OR m.dari_ruangan_id = room OR m.ke_ruangan_id = room)
          AND (aset IS NULL OR m.barang_aset_id = aset)
          AND (date_from IS NULL OR m.tanggal >= date_from)
          AND (date_to IS NULL OR m.tanggal <= date_to)
    )
    SELECT jsonb_build_object(
        'total', (SELECT count(*) FROM matched),
        'rows', coalesce((SELECT jsonb_agg(to_jsonb(r) ORDER BY r.tanggal DESC, r.id DESC)
            FROM (SELECT * FROM matched ORDER BY tanggal DESC, id DESC
                  LIMIT CASE WHEN page_number = 0 THEN NULL ELSE 15 END
                  OFFSET CASE WHEN page_number = 0 THEN 0 ELSE (page_number - 1) * 15 END) r), '[]')
    ) INTO result;
    RETURN result;
END;
$function$;

REVOKE ALL ON FUNCTION simbar.record_mutasi_aset() FROM PUBLIC, anon, authenticated, service_role;
DO $grants$
DECLARE
    signature text;
BEGIN
    FOREACH signature IN ARRAY ARRAY[
        'public.simbar_mutasi_aset_move(bigint[], bigint, date, text)',
        'public.simbar_mutasi_aset_list(jsonb, integer)'
    ] LOOP
        EXECUTE 'REVOKE ALL ON FUNCTION ' || signature || ' FROM PUBLIC, anon, authenticated, service_role';
        EXECUTE 'GRANT EXECUTE ON FUNCTION ' || signature || ' TO authenticated';
    END LOOP;
END;
$grants$;

COMMIT;
