DROP TRIGGER IF EXISTS push_events ON simbar.pemeliharaan_aset;
CREATE TRIGGER push_events AFTER INSERT OR UPDATE OF status ON simbar.pemeliharaan_aset FOR EACH ROW EXECUTE FUNCTION simbar.push_on_pemeliharaan();

