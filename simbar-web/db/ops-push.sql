CREATE OR REPLACE FUNCTION simbar.push_on_pemeliharaan()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    who text := coalesce((SELECT name FROM simbar.users WHERE id = NEW.created_by), 'Seseorang');
    what text := coalesce((SELECT nama_aset FROM simbar.barang_aset WHERE id = NEW.barang_aset_id), 'aset');
    lines jsonb := '{"proses": "sedang dikerjakan", "selesai": "sudah selesai", "rusak": "dinyatakan rusak"}';
BEGIN
    IF TG_OP = 'INSERT' AND NEW.status = 'menunggu' THEN
        PERFORM simbar.push_queue(simbar.warehouse_people(), 'pemeliharaan-new', 'Laporan pemeliharaan baru',
            who || ' melaporkan pemeliharaan ' || what || '.', 'Ada {n} laporan pemeliharaan baru.', '/?menu=pemeliharaan');
    ELSIF TG_OP = 'UPDATE' AND OLD.status IS DISTINCT FROM NEW.status AND lines ? NEW.status THEN
        PERFORM simbar.push_queue(ARRAY[NEW.created_by], 'pemeliharaan-' || NEW.status, 'Pemeliharaan ' || (lines ->> NEW.status),
            'Pemeliharaan ' || what || ' ' || (lines ->> NEW.status) || '.', '{n} pemeliharaan yang Anda laporkan ' || (lines ->> NEW.status) || '.', '/?menu=pemeliharaan');
    END IF;
    RETURN NULL;
END;
$function$;

DROP TRIGGER IF EXISTS push_events ON simbar.stock_out_requests;
CREATE TRIGGER push_events AFTER INSERT OR UPDATE OF status ON simbar.stock_out_requests FOR EACH ROW EXECUTE FUNCTION simbar.push_on_pickup();
