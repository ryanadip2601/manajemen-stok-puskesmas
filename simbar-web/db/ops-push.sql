CREATE TRIGGER push_events AFTER INSERT OR UPDATE OF status ON simbar.permintaan_barang FOR EACH ROW EXECUTE FUNCTION simbar.push_on_permintaan();
DROP TRIGGER IF EXISTS push_events ON simbar.usulan_penerimaan_barang;
