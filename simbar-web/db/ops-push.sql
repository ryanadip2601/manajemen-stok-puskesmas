CREATE OR REPLACE FUNCTION public.simbar_push_subscribe(sub_endpoint text, sub_p256dh text, sub_auth text, agent text DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    actor simbar.users%ROWTYPE := simbar.require_profile(ARRAY['admin', 'admin_gudang', 'staff']);
BEGIN
    IF sub_endpoint !~ '^https://\S+$' OR char_length(sub_endpoint) > 1000
        OR sub_p256dh !~ '^[A-Za-z0-9_=-]{40,200}$' OR sub_auth !~ '^[A-Za-z0-9_=-]{8,100}$' THEN
        RAISE check_violation USING MESSAGE = 'Data langganan notifikasi tidak valid.';
    END IF;
    INSERT INTO simbar.push_subscriptions (user_id, endpoint, p256dh, auth, user_agent)
    VALUES (actor.id, sub_endpoint, sub_p256dh, sub_auth, left(agent, 300))
    ON CONFLICT (endpoint) DO UPDATE SET user_id = excluded.user_id, p256dh = excluded.p256dh, auth = excluded.auth,
        user_agent = excluded.user_agent, last_seen_at = now();
    RETURN simbar.push_badge(actor.id);
END;
$function$;

CREATE OR REPLACE FUNCTION public.simbar_push_unsubscribe(sub_endpoint text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    actor simbar.users%ROWTYPE := simbar.require_profile(ARRAY['admin', 'admin_gudang', 'staff']);
BEGIN
    DELETE FROM simbar.push_subscriptions WHERE endpoint = sub_endpoint AND user_id = actor.id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.simbar_my_badge()
RETURNS integer
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    actor simbar.users%ROWTYPE := simbar.require_profile(ARRAY['admin', 'admin_gudang', 'staff']);
BEGIN
    RETURN simbar.push_badge(actor.id);
END;
$function$;

-- /api/notify removes subscriptions the push service reports as gone; it proves itself with the shared secret.
CREATE OR REPLACE FUNCTION public.simbar_push_forget(notify_secret text, endpoints text[])
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    removed integer;
BEGIN
    IF notify_secret IS NULL OR notify_secret IS DISTINCT FROM (SELECT value FROM simbar.push_settings WHERE key = 'notify_secret') THEN
        RAISE insufficient_privilege USING MESSAGE = 'Akses ditolak.';
    END IF;
    DELETE FROM simbar.push_subscriptions WHERE endpoint = ANY (endpoints[1:200]);
    GET DIAGNOSTICS removed = ROW_COUNT;
    RETURN removed;
END;
$function$;

REVOKE ALL ON TABLE simbar.push_settings, simbar.push_subscriptions, simbar.push_outbox FROM PUBLIC, anon, authenticated;
DO $grants$
DECLARE
    signature text;
BEGIN
    FOREACH signature IN ARRAY ARRAY['simbar.push_badge(bigint)', 'simbar.push_queue(bigint[], text, text, text, text, text)',
        'simbar.warehouse_people()', 'simbar.push_dispatch()', 'simbar.push_on_pickup()', 'simbar.push_on_permintaan()',
        'simbar.push_on_usulan()', 'simbar.push_on_pemeliharaan()'] LOOP
        EXECUTE 'REVOKE ALL ON FUNCTION ' || signature || ' FROM PUBLIC, anon, authenticated, service_role';
    END LOOP;
    FOREACH signature IN ARRAY ARRAY['public.simbar_push_subscribe(text, text, text, text)', 'public.simbar_push_unsubscribe(text)',
        'public.simbar_my_badge()'] LOOP
        EXECUTE 'REVOKE ALL ON FUNCTION ' || signature || ' FROM PUBLIC, anon, authenticated, service_role';
        EXECUTE 'GRANT EXECUTE ON FUNCTION ' || signature || ' TO authenticated';
    END LOOP;
    REVOKE ALL ON FUNCTION public.simbar_push_forget(text, text[]) FROM PUBLIC, anon, authenticated, service_role;
    GRANT EXECUTE ON FUNCTION public.simbar_push_forget(text, text[]) TO anon;
END;
$grants$;

COMMIT;
