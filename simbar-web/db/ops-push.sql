CREATE OR REPLACE FUNCTION simbar.push_on_pickup()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    who text := (SELECT name FROM simbar.users WHERE id = NEW.user_id);
    what text := (SELECT i.name || ' (' || NEW.quantity || ' ' || coalesce(u.symbol, '') || ')' FROM simbar.items i
        LEFT JOIN simbar.units u ON u.id = i.unit_id WHERE i.id = NEW.item_id);
BEGIN
    IF TG_OP = 'INSERT' AND NEW.status = 'pending' THEN
        PERFORM simbar.push_queue(simbar.warehouse_people(), 'pickup-new', 'Pengambilan barang baru',
            who || ' mengajukan pengambilan ' || what || '.', who || ' mengajukan pengambilan {n} barang.', '/?menu=checklist');
    ELSIF TG_OP = 'UPDATE' AND OLD.status = 'pending' AND NEW.status IN ('approved', 'completed') THEN
        PERFORM simbar.push_queue(ARRAY[NEW.user_id], 'pickup-approved', 'Pengambilan barang disetujui',
            what || ' sudah disetujui dan dicatat keluar.', '{n} barang yang Anda ajukan sudah disetujui.', '/?menu=pickup');
    ELSIF TG_OP = 'UPDATE' AND OLD.status = 'pending' AND NEW.status = 'rejected' THEN
        PERFORM simbar.push_queue(ARRAY[NEW.user_id], 'pickup-rejected', 'Pengambilan barang ditolak',
            what || ' ditolak' || coalesce(': ' || nullif(NEW.reject_reason, ''), '') || '.', '{n} pengambilan barang Anda ditolak.', '/?menu=pickup');
    END IF;
    RETURN NULL;
END;
$function$;

CREATE OR REPLACE FUNCTION simbar.push_on_permintaan()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    who text := (SELECT name FROM simbar.users WHERE id = NEW.user_id);
    what text := NEW.nama_barang || ' (' || NEW.jumlah || ')';
    titles jsonb := '{"diproses": "Permintaan barang diproses", "disetujui": "Permintaan barang disetujui", "ditolak": "Permintaan barang ditolak",
        "revisi": "Permintaan barang perlu direvisi", "tersedia": "Barang permintaan sudah tersedia"}';
    lines jsonb := '{"diproses": "sedang diproses gudang", "disetujui": "sudah disetujui", "ditolak": "ditolak",
        "revisi": "perlu direvisi, buka untuk melihat catatan", "tersedia": "sudah tersedia dan siap diambil"}';
BEGIN
    IF (TG_OP = 'INSERT' AND NEW.status = 'pending') OR (TG_OP = 'UPDATE' AND OLD.status = 'revisi' AND NEW.status = 'pending') THEN
        PERFORM simbar.push_queue(simbar.warehouse_people(), 'bhp-new', 'Permintaan barang ' || CASE WHEN TG_OP = 'INSERT' THEN 'baru' ELSE 'diperbarui' END,
            who || ' meminta ' || what || '.', 'Ada {n} permintaan barang baru.', '/?menu=verifikasi');
    ELSIF TG_OP = 'UPDATE' AND OLD.status IS DISTINCT FROM NEW.status AND titles ? NEW.status THEN
        PERFORM simbar.push_queue(ARRAY[NEW.user_id], 'bhp-' || NEW.status, titles ->> NEW.status,
            'Permintaan ' || what || ' ' || (lines ->> NEW.status) || '.', '{n} permintaan barang Anda ' || (lines ->> NEW.status) || '.', '/?menu=permintaan');
    END IF;
    RETURN NULL;
END;
$function$;

