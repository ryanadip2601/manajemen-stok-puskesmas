-- Push notifications for the installed app (PWA). Safe to re-run.
-- New requests notify the warehouse (admin, admin_gudang); status changes notify whoever submitted the request.
-- Events from one transaction are merged per recipient (one notification for a pickup of five items) and sent
-- at commit through pg_net to /api/notify, which signs and delivers them with the VAPID key.
-- The notify URL and shared secret live in simbar.push_settings and are written outside this file.

BEGIN;

DO $extension$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'pg_net') THEN
        CREATE EXTENSION IF NOT EXISTS pg_net;
    END IF;
END;
$extension$;

CREATE TABLE IF NOT EXISTS simbar.push_settings (
    key text PRIMARY KEY,
    value text NOT NULL
);

CREATE TABLE IF NOT EXISTS simbar.push_subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES simbar.users(id) ON DELETE CASCADE,
    endpoint text NOT NULL UNIQUE,
    p256dh text NOT NULL,
    auth text NOT NULL,
    user_agent text,
    created_at timestamptz NOT NULL DEFAULT now(),
    last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS push_subscriptions_user_idx ON simbar.push_subscriptions (user_id);

CREATE TABLE IF NOT EXISTS simbar.push_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tx bigint NOT NULL DEFAULT txid_current(),
    recipient bigint NOT NULL REFERENCES simbar.users(id) ON DELETE CASCADE,
    topic text NOT NULL,
    title text NOT NULL,
    body_one text NOT NULL,
    body_many text NOT NULL,
    url text NOT NULL,
    items integer NOT NULL DEFAULT 1,
    UNIQUE (tx, recipient, topic)
);

-- Number shown on the app icon: open work for the warehouse, things waiting on the person for everyone else.
CREATE OR REPLACE FUNCTION simbar.push_badge(person bigint)
RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $function$
    SELECT CASE WHEN u.role IN ('admin', 'admin_gudang') THEN
        (SELECT count(*) FROM simbar.stock_out_requests WHERE status = 'pending')
        + (SELECT count(*) FROM simbar.permintaan_barang WHERE status IN ('pending', 'diproses'))
        + (SELECT count(*) FROM simbar.usulan_penerimaan_barang WHERE status IN ('pending', 'diproses'))
        + (SELECT count(*) FROM simbar.pemeliharaan_aset WHERE status = 'menunggu')
    ELSE
        (SELECT count(*) FROM simbar.permintaan_barang WHERE user_id = u.id AND status IN ('tersedia', 'revisi'))
        + (SELECT count(*) FROM simbar.usulan_penerimaan_barang WHERE user_id = u.id AND status = 'revisi')
    END::integer
    FROM simbar.users u WHERE u.id = person;
$function$;

-- Queue a notification for some people in the current transaction; repeats of the same topic add up.
CREATE OR REPLACE FUNCTION simbar.push_queue(recipients bigint[], push_topic text, push_title text, one text, many text, push_url text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    actor_id bigint := (SELECT id FROM simbar.users WHERE auth_user_id = auth.uid());
BEGIN
    INSERT INTO simbar.push_outbox (recipient, topic, title, body_one, body_many, url)
    SELECT DISTINCT r, push_topic, push_title, one, many, push_url FROM unnest(recipients) AS r
    WHERE r IS NOT NULL AND r IS DISTINCT FROM actor_id
      AND EXISTS (SELECT 1 FROM simbar.push_subscriptions s WHERE s.user_id = r)
    ON CONFLICT (tx, recipient, topic) DO UPDATE SET items = simbar.push_outbox.items + 1;
END;
$function$;

CREATE OR REPLACE FUNCTION simbar.warehouse_people()
RETURNS bigint[]
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $function$ SELECT coalesce(array_agg(id), '{}') FROM simbar.users WHERE is_approved AND role IN ('admin', 'admin_gudang'); $function$;

-- Runs once per queued row when the transaction commits: sends one request to /api/notify.
CREATE OR REPLACE FUNCTION simbar.push_dispatch()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    queued simbar.push_outbox%ROWTYPE;
    target text := (SELECT value FROM simbar.push_settings WHERE key = 'notify_url');
    secret text := (SELECT value FROM simbar.push_settings WHERE key = 'notify_secret');
    messages jsonb;
BEGIN
    DELETE FROM simbar.push_outbox WHERE id = NEW.id RETURNING * INTO queued;
    IF NOT FOUND OR target IS NULL OR secret IS NULL THEN
        RETURN NULL;
    END IF;
    SELECT jsonb_agg(jsonb_build_object(
        'subscription', jsonb_build_object('endpoint', s.endpoint, 'keys', jsonb_build_object('p256dh', s.p256dh, 'auth', s.auth)),
        'payload', jsonb_build_object('title', queued.title,
            'body', CASE WHEN queued.items > 1 THEN replace(queued.body_many, '{n}', queued.items::text) ELSE queued.body_one END,
            'url', queued.url, 'tag', queued.topic, 'badge', simbar.push_badge(queued.recipient))))
    INTO messages
    FROM simbar.push_subscriptions s WHERE s.user_id = queued.recipient;
    IF messages IS NOT NULL THEN
        PERFORM net.http_post(url := target, body := jsonb_build_object('messages', messages),
            headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || secret),
            timeout_milliseconds := 8000);
    END IF;
    RETURN NULL;
EXCEPTION WHEN OTHERS THEN
    -- A notification must never undo the request that caused it.
    RAISE WARNING 'SIMBAR push not sent: %', SQLERRM;
    RETURN NULL;
END;
$function$;

DROP TRIGGER IF EXISTS push_outbox_dispatch ON simbar.push_outbox;
CREATE CONSTRAINT TRIGGER push_outbox_dispatch AFTER INSERT ON simbar.push_outbox
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION simbar.push_dispatch();

